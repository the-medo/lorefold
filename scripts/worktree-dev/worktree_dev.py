#!/usr/bin/env python3
"""Linux/WSL worktree infrastructure; Python stdlib and local Docker only."""

import argparse
from contextlib import contextmanager
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import shlex
import socket
import subprocess
import sys
import tempfile
import time
import runtime


IMAGE = "postgres:16-alpine"
LABEL = "com.lorefold.dev"
MARKER = "# Generated by lorefold-worktree-dev; do not edit or copy.\n"
PORT_RANGES = {"database": (15432, 15531), "backend": (13000, 13099), "frontend": (15173, 15272)}


class DevError(Exception):
    pass


def command(args, *, check=True, **kwargs):
    result = subprocess.run(args, text=True, capture_output=True, **kwargs)
    if check and result.returncode:
        # Commands never include passwords. Avoid printing inherited env or state.
        raise DevError(f"{args[0]} failed: {result.stderr.strip() or result.stdout.strip()}")
    return result


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()[:12]


def identity(root, common):
    repo_id = digest(str(common))
    worktree_id = digest(f"{common}\n{root}")
    stem = f"lorefold-{repo_id}-{worktree_id}"
    return {"repo_id": repo_id, "id": worktree_id, "root": str(root), "common": str(common),
            "container": f"{stem}-db", "volume": f"{stem}-pgdata"}


def atomic_write(path, content):
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".tmp-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_json(path):
    try:
        return json.loads(path.read_text())
    except (ValueError, OSError) as exc:
        raise DevError(f"Cannot read state file {path}: {exc}") from exc


def parse_env(path):
    """Read a small dotenv subset; never execute shell code or expand variables."""
    values = {}
    if not path.exists():
        return values
    for number, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:]
        key, sep, raw = line.partition("=")
        key = key.strip()
        if not sep or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise DevError(f"Invalid environment assignment in {path}:{number}")
        raw = raw.strip()
        if raw.startswith(("'", '"')):
            try:
                parts = shlex.split(raw, comments=True)
            except ValueError as exc:
                raise DevError(f"Invalid quoted value in {path}:{number}") from exc
            if len(parts) != 1:
                raise DevError(f"Expected one quoted value in {path}:{number}")
            values[key] = parts[0]
        else:
            values[key] = raw.split(" #", 1)[0].rstrip()
    return values


def env_text(values):
    # shlex quoting also preserves spaces and literal shell syntax in checkout paths.
    return MARKER + "".join(f"{key}={shlex.quote(str(value))}\n" for key, value in values.items())


GOOGLE_KEYS = ("GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET")


def google_profile_path():
    return runtime.profile_path().with_name("google.env")


def google_credentials(values):
    credentials = {key: values.get(key, "").strip() for key in GOOGLE_KEYS}
    if not all(credentials.values()):
        raise DevError("Set both GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET before configuring shared Google sign-in.")
    return credentials


def configure_google(source):
    # Explicit opt-in, restricted to this app's two development OAuth values.
    # Database, session, cloud provider, and other application secrets stay local.
    credentials = google_credentials(parse_env(source))
    atomic_write(google_profile_path(), env_text(credentials))


def seed_google_credentials(template):
    profile = google_profile_path()
    if not profile.exists():
        return template
    values = parse_env(profile)
    if set(values) != set(GOOGLE_KEYS):
        raise DevError("The shared Google profile must contain only GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET.")
    for key, value in google_credentials(values).items():
        assignment = f"{key}={shlex.quote(value)}"
        pattern = rf"(?m)^[ \t]*(?:export[ \t]+)?{key}[ \t]*=[^\r\n]*"
        if re.search(pattern, template):
            template = re.sub(pattern, lambda match: assignment, template)
        else:
            template = template.rstrip("\n") + "\n" + assignment + "\n"
    return template


class Worktrees:
    def __init__(self):
        script_root = Path(__file__).resolve().parents[2]
        root = Path(command(["git", "rev-parse", "--show-toplevel"], cwd=script_root).stdout.strip()).resolve()
        if root != script_root:
            raise DevError("Install this launcher under scripts/worktree-dev in the intended Git checkout.")
        common = Path(command(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=root).stdout.strip()).resolve()
        self.root = root
        self.expected = identity(root, common)
        default = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state")) / "lorefold/worktrees"
        self.registry = Path(os.environ.get("LOREFOLD_DEV_REGISTRY", default)).expanduser().resolve()
        self.local_state = root / ".lorefold/state.json"
        self.record = self.registry / f"{self.expected['id']}.json"

    @contextmanager
    def lock(self):
        self.registry.mkdir(mode=0o700, parents=True, exist_ok=True)
        with open(self.registry / "registry.lock", "a+") as stream:
            os.chmod(stream.name, 0o600)
            fcntl.flock(stream, fcntl.LOCK_EX)
            yield

    def docker_ready(self):
        # Docker gives DOCKER_CONTEXT priority over DOCKER_HOST.
        host = None if os.environ.get("DOCKER_CONTEXT") else os.environ.get("DOCKER_HOST")
        if not host:
            host = command(["docker", "context", "inspect", "--format", '{{(index .Endpoints "docker").Host}}']).stdout.strip()
        if not host.startswith("unix://"):
            raise DevError("Use a local Docker daemon (unix socket), not a remote Docker context.")
        command(["docker", "info", "--format", "{{.ServerVersion}}"])

    def inspect(self, kind, name):
        result = command(["docker", kind, "inspect", name], check=False)
        if result.returncode:
            if re.search(r"no such (object|container|volume)", result.stderr, re.I):
                return None
            raise DevError(f"Cannot inspect Docker {kind} {name}: {result.stderr.strip()}")
        return json.loads(result.stdout)[0]

    def validate(self, state, expected=None):
        if not isinstance(state, dict) or state.get("version") != 1:
            raise DevError("Unsupported worktree state; refusing to alter resources.")
        wanted = expected or identity(Path(state["root"]), Path(state["common"]))
        if any(state.get(key) != value for key, value in wanted.items()):
            raise DevError("Worktree identity mismatch. Never copy .lorefold or generated environment files.")
        if state.get("image") != IMAGE:
            raise DevError("Database image differs from recorded state; migrate deliberately before upgrading.")
        if type(state.get("provisioned")) is not bool:
            raise DevError("Invalid database provisioning state.")
        ports = state.get("ports", {})
        if set(ports) != set(PORT_RANGES) or any(
            type(ports[key]) is not int or not low <= ports[key] <= high
            for key, (low, high) in PORT_RANGES.items()
        ):
            raise DevError("Invalid port reservations; refusing to alter resources.")
        if not all(re.fullmatch(r"[0-9a-f]{64}", state.get(key, "")) for key in ("password", "auth_secret")):
            raise DevError("Invalid generated credentials in local state.")
        runtime.origin(state.get("access", {}), ports["frontend"])

    def load(self, required=True):
        shared = read_json(self.record) if self.record.exists() else None
        local = read_json(self.local_state) if self.local_state.exists() else None
        for state in (shared, local):
            if state is not None:
                self.validate(state, self.expected)
        if shared is not None and local is not None and shared != local:
            raise DevError("Registry and local state disagree; refusing to alter resources.")
        state = shared or local
        if state is None and required:
            raise DevError("This worktree is not configured. Run setup first.")
        return state

    def labels(self, state):
        return {f"{LABEL}.managed": "true", f"{LABEL}.repo": state["repo_id"],
                f"{LABEL}.worktree": state["id"], f"{LABEL}.path": state["root"]}

    def owned(self, state, kind):
        item = self.inspect(kind, state["container" if kind == "container" else "volume"])
        if item is None:
            return None
        labels = (item.get("Config", {}).get("Labels") if kind == "container" else item.get("Labels")) or {}
        if any(labels.get(key) != value for key, value in self.labels(state).items()):
            raise DevError(f"Docker {kind} ownership mismatch; refusing to touch {item.get('Name', '')}.")
        if kind == "container":
            binding = item["HostConfig"].get("PortBindings", {}).get("5432/tcp")
            expected = [{"HostIp": "127.0.0.1", "HostPort": str(state["ports"]["database"])}]
            mounted = any(m.get("Name") == state["volume"] and m.get("Destination") == "/var/lib/postgresql/data"
                          for m in item.get("Mounts", []))
            if binding != expected or not mounted or item["Config"]["Image"] != state["image"]:
                raise DevError("Database container configuration differs from owned state; refusing to alter it.")
        return item

    def records(self):
        states = []
        for path in sorted(self.registry.glob("*.json")):
            state = read_json(path)
            self.validate(state)
            if path.name != f"{state['id']}.json":
                raise DevError(f"Registry filename mismatch: {path}")
            states.append(state)
        return states

    def reserve_ports(self):
        used = {port for state in self.records() for port in state["ports"].values()}
        ports = {}
        for key, (low, high) in PORT_RANGES.items():
            width = high - low + 1
            start = int(self.expected["id"], 16) % width
            for offset in range(width):
                port = low + (start + offset) % width
                if port in used:
                    continue
                with socket.socket() as sock:
                    try:
                        sock.bind(("127.0.0.1", port))
                    except OSError:
                        continue
                ports[key] = port
                used.add(port)
                break
            else:
                raise DevError(f"No available {key} ports in {low}-{high}. Purge unused worktrees explicitly.")
        return ports

    def save(self, state):
        content = json.dumps(state, indent=2) + "\n"
        atomic_write(self.record, content)
        atomic_write(self.local_state, content)

    def generated_env(self, state):
        ports = state["ports"]
        origin = runtime.origin(state.get("access", {}), ports["frontend"])
        return {
            "NODE_ENV": "development", "LOREFOLD_WORKTREE_ID": state["id"],
            "DATABASE_URL": f"postgresql://lorefold:{state['password']}@127.0.0.1:{ports['database']}/lorefold",
            "PGHOST": "127.0.0.1", "PGPORT": str(ports["database"]), "PGUSER": "lorefold",
            "PGDATABASE": "lorefold", "PGPASSWORD": state["password"],
            "HOST": "127.0.0.1", "PORT": str(ports["backend"]), "FRONTEND_PORT": str(ports["frontend"]),
            "APP_ORIGIN": origin, "BETTER_AUTH_URL": origin, "BETTER_AUTH_SECRET": state["auth_secret"],
            "AUTH_COOKIE_PREFIX": f"lorefold-{state['id']}",
            "R2_KEY_PREFIX": f"dev/{state['repo_id']}/{state['id']}/",
            "LOREFOLD_LOCAL_STORAGE_DIR": str(self.root / ".lorefold/storage"),
            "IMPORT_CONCURRENCY": "1",
        }

    def frontend_env(self, state):
        return {
            "VITE_HOST": "127.0.0.1", "VITE_PORT": state["ports"]["frontend"],
            "VITE_API_BASE_URL": "/api",
            "VITE_API_PROXY_TARGET": f"http://127.0.0.1:{state['ports']['backend']}",
        }

    def write_environment(self, state):
        atomic_write(self.root / ".env.worktree", env_text(self.generated_env(state)))
        atomic_write(self.root / "frontend/.env.worktree", env_text(self.frontend_env(state)))
        atomic_write(self.root / ".lorefold/postgres.env",
                     f"POSTGRES_USER=lorefold\nPOSTGRES_DB=lorefold\nPOSTGRES_PASSWORD={state['password']}\n")
        target = self.root / ".env"
        if not target.exists():
            template = seed_google_credentials((self.root / ".env.example").read_text())
            # Exclusive creation preserves user config if another editor creates it.
            try:
                fd = os.open(target, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            except FileExistsError:
                pass
            else:
                with os.fdopen(fd, "w") as stream:
                    stream.write(template)
        (self.root / ".lorefold/storage").mkdir(mode=0o700, exist_ok=True)

    def setup(self):
        state = self.load(required=False)
        if state is None:
            for kind, name in (("container", self.expected["container"]), ("volume", self.expected["volume"])):
                if self.inspect(kind, name) is not None:
                    raise DevError("Docker resources exist but local state is missing. Recover state before continuing.")
            state = {"version": 1, **self.expected, "image": IMAGE, "ports": self.reserve_ports(),
                     "password": secrets.token_hex(32), "auth_secret": secrets.token_hex(32), "provisioned": False,
                     "access": runtime.load_access()}
        # Validate both resources before making any changes, including restarting.
        container = self.owned(state, "container")
        volume = self.owned(state, "volume")
        if (container or state["provisioned"]) and not volume:
            raise DevError("Database volume is missing; refusing to start with empty data.")
        self.save(state)
        self.write_environment(state)
        label_args = [part for key, value in self.labels(state).items() for part in ("--label", f"{key}={value}")]
        if not volume:
            command(["docker", "volume", "create", *label_args, state["volume"]])
        if not container:
            command(["docker", "create", "--name", state["container"], *label_args,
                     "--env-file", str(self.root / ".lorefold/postgres.env"),
                     "--publish", f"127.0.0.1:{state['ports']['database']}:5432",
                     "--mount", f"type=volume,source={state['volume']},target=/var/lib/postgresql/data",
                     "--health-cmd", "pg_isready -h 127.0.0.1 -U lorefold -d lorefold",
                     "--health-interval", "2s", "--health-timeout", "2s", "--health-retries", "30",
                     "--memory", "512m", "--cpus", "1", state["image"]])
            container = self.owned(state, "container")
        if not container["State"]["Running"]:
            # A reservation is not a listening socket. Fail without changing the port
            # if a different application claimed it while this DB was stopped.
            with socket.socket() as sock:
                # Connections closed during down may still be in TIME_WAIT.
                # Match Docker's reusable listener without accepting a live owner.
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                try:
                    sock.bind(("127.0.0.1", state["ports"]["database"]))
                    sock.listen()
                except OSError as exc:
                    raise DevError("Reserved database port is occupied. Stop its owner before restarting this DB.") from exc
            command(["docker", "start", state["container"]])
        deadline = time.monotonic() + 60
        while time.monotonic() < deadline:
            check = command(self.sql_command(state, ["-Atqc", "SELECT 1"]), check=False,
                            env={**os.environ, "PGPASSWORD": state["password"]})
            if check.returncode == 0 and check.stdout.strip() == "1":
                state["provisioned"] = True
                self.save(state)
                return state
            time.sleep(0.5)
        raise DevError("PostgreSQL did not become ready within 60 seconds. Inspect this worktree's logs.")

    def sql_command(self, state, arguments, interactive=False):
        options = ["-i"] if interactive else []
        if interactive and sys.stdin.isatty():
            options.append("-t")
        return ["docker", "exec", *options, "--env", "PGPASSWORD", state["container"],
                "psql", "-h", "127.0.0.1", "-U", "lorefold", "-d", "lorefold",
                "--set", "ON_ERROR_STOP=1", *arguments]

    def require_running(self, state):
        item = self.owned(state, "container")
        volume = self.owned(state, "volume")
        if not item or not volume or not item["State"]["Running"]:
            raise DevError("Database is not running. Run up first.")

    def status(self, state, as_json=False):
        if state is None:
            data = {"configured": False, "root": str(self.root)}
        else:
            container = self.owned(state, "container")
            volume = self.owned(state, "volume")
            data = {key: state[key] for key in ("id", "root", "container", "volume", "ports")}
            data.update(configured=True, database_state=container["State"]["Status"] if container else "missing",
                        volume_exists=volume is not None,
                        app_origin=runtime.origin(state.get("access", {}), state['ports']['frontend']),
                        app_implemented=(self.root / "backend/index.ts").is_file(),
                        app_service=runtime.service(state), service_unit=runtime.unit(state),
                        app_status="healthy" if runtime.healthy(f"http://127.0.0.1:{state['ports']['frontend']}/api/health") else "unavailable",
                        access_profile=str(runtime.profile_path()),
                        environment_file=str(self.root / ".env.worktree"))
        if as_json:
            print(json.dumps(data, indent=2))
        elif state is None:
            print("This worktree is not configured. Run setup first.")
        else:
            print(f"Worktree: {state['root']}\nDatabase: {state['container']} ({data['database_state']})")
            print(f"PostgreSQL: 127.0.0.1:{state['ports']['database']} / lorefold\nVolume: {state['volume']}")
            print(f"Loopback API: http://127.0.0.1:{state['ports']['backend']}\nBrowser URL: {data['app_origin']}")
            print(f"Application: {data['app_status']}; background service: {data['app_service']}")
            print("Environment: .env + generated .env.worktree (use the run command)")

    def down(self, state, purge=False, local=True):
        # Check every target before stopping/removing any resource.
        container = self.owned(state, "container")
        volume = self.owned(state, "volume")
        runtime.stop(state)
        if container:
            if container["State"]["Running"]:
                command(["docker", "stop", "--time", "10", container["Id"]])
            if purge:
                command(["docker", "container", "rm", container["Id"]])
        if purge:
            if volume:
                # Revalidate immediately before deleting the named volume.
                self.owned(state, "volume")
                command(["docker", "volume", "rm", state["volume"]])
            (self.registry / f"{state['id']}.json").unlink(missing_ok=True)
            if local:
                self.local_state.unlink(missing_ok=True)
                (self.root / ".lorefold/postgres.env").unlink(missing_ok=True)
                for path in (self.root / ".env.worktree", self.root / "frontend/.env.worktree"):
                    if path.exists() and path.read_text().startswith(MARKER):
                        path.unlink()
            print(f"Purged PostgreSQL resources and reservations: {state['id']}")
        else:
            print(f"Stopped {state['container']}; database data and reservations retained.")

    def prune(self, confirmed):
        candidates = [s for s in self.records() if s["repo_id"] == self.expected["repo_id"] and not Path(s["root"]).exists()]
        # Preflight the entire list; never leave a partially acted-on ownership conflict.
        for state in candidates:
            self.owned(state, "container")
            self.owned(state, "volume")
            runtime.service(state)
            runtime.serve_state(state)
            print(f"Stale: {state['root']}\n  {state['container']}\n  {state['volume']}")
        if not candidates:
            print("No stale worktrees for this repository.")
        elif not confirmed:
            print("Dry run only. Use prune --yes to remove exactly these PostgreSQL resources.")
        else:
            for state in candidates:
                # The path may have been restored while Docker was responding.
                if Path(state["root"]).exists():
                    raise DevError("A stale worktree path reappeared; refusing to prune it.")
                self.down(state, purge=True, local=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("setup", help="Create/reuse PostgreSQL and generate local env files.")
    sub.add_parser("up", help="Start PostgreSQL, a background app service, and configured private access.")
    access = sub.add_parser("configure-access", help="Save this machine's default browser access for future worktrees.")
    access.add_argument("--origin-template", required=True)
    access.add_argument("--tailscale-serve", action="store_true")
    google = sub.add_parser("configure-google", help="Save this app's development Google credentials for new worktrees.")
    google.add_argument("--from-env", default=".env", help="Read GOOGLE_CLIENT_ID and GOOGLE_CLIENT_SECRET from this dotenv file.")
    sub.add_parser("status", help="Show owned resources; never prints credentials.").add_argument("--json", action="store_true")
    sub.add_parser("logs", help="Show recent database logs.")
    sub.add_parser("down", help="Stop this worktree's app, private route, and PostgreSQL; keep data.").add_argument("--purge-data", action="store_true")
    sub.add_parser("prune", help="List resources of deleted worktrees; dry-run by default.").add_argument("--yes", action="store_true")
    sub.add_parser("run", help="Run a foreground command with .env then worktree overrides.").add_argument("command", nargs=argparse.REMAINDER)
    sub.add_parser("psql", help="Connect to this worktree's PostgreSQL using the container client.").add_argument("arguments", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    workspace = Worktrees()
    launch = None
    starting = None
    with workspace.lock():
        if args.action == "configure-google":
            configure_google(workspace.root / args.from_env)
            print(f"Saved private Google profile: {google_profile_path()}\nNew .env files inherit these two values. Existing .env files are unchanged.")
            return
        if args.action == "configure-access":
            profile = {"origin_template": args.origin_template, "tailscale_serve": args.tailscale_serve}
            runtime.origin(profile, 15173)
            runtime.check_access({"access": profile, "ports": {"frontend": 15173}}, check_route=False)
            atomic_write(runtime.profile_path(), json.dumps(profile, indent=2) + "\n")
            print(f"Saved access profile: {runtime.profile_path()}\nNew worktrees inherit it. Use down then up to update existing worktrees.")
            return
        workspace.docker_ready()
        if args.action in ("setup", "up"):
            state = workspace.setup()
            if args.action == "up":
                if runtime.service(state) not in ("active", "activating"):
                    # Preserve active services' origins. Stopped worktrees adopt
                    # the machine default without copying per-worktree secrets.
                    mapping = runtime.serve_state(state)
                    access = runtime.load_access()
                    if access != state.get("access", {}) and mapping == "ready":
                        raise DevError("Run down before switching this worktree's existing private route to another access profile.")
                    state["access"] = access
                    runtime.check_access(state)
                    workspace.save(state)
                    workspace.write_environment(state)
                runtime.start(state)
                starting = state
            else:
                workspace.status(state)
        elif args.action == "status":
            workspace.status(workspace.load(required=False), args.json)
        elif args.action == "prune":
            workspace.prune(args.yes)
        else:
            state = workspace.load()
            if args.action == "down":
                workspace.down(state, args.purge_data)
            elif args.action == "logs":
                if not workspace.owned(state, "container"):
                    raise DevError("Database container is missing.")
                result = command(["docker", "logs", "--tail", "100", state["container"]])
                print(result.stdout, end="")
                print(result.stderr, end="", file=sys.stderr)
            elif args.action == "psql":
                workspace.require_running(state)
                arguments = args.arguments[1:] if args.arguments[:1] == ["--"] else args.arguments
                launch = (workspace.sql_command(state, arguments, interactive=True), {**os.environ, "PGPASSWORD": state["password"]})
            elif args.action == "run":
                workspace.require_running(state)
                arguments = args.command[1:] if args.command[:1] == ["--"] else args.command
                if not arguments:
                    raise DevError("Provide a command after run --.")
                env = {**os.environ, **parse_env(workspace.root / ".env"), **workspace.generated_env(state),
                       **{key: str(value) for key, value in workspace.frontend_env(state).items()}}
                launch = (arguments, env)
    if starting:
        # The background launcher needs the registry lock to load its environment.
        # Wait only after releasing it, and report success only after HTTP readiness.
        runtime.wait_ready(starting)
        workspace.status(starting)
    if launch:
        # Release the registry lock before running a potentially long-lived app.
        os.chdir(workspace.root)
        os.execvpe(launch[0][0], launch[0], launch[1])


if __name__ == "__main__":
    try:
        main()
    except (DevError, runtime.RuntimeError, OSError, KeyError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)
    except KeyboardInterrupt:
        sys.exit(130)
